  private initSelfPeer() {
    const selfPublicKey = this.ctx.get(KeyService).getSelfPublicKey();
    this.peers.set(
      Hash.digest(selfPublicKey).toPrimitive(),
      {
        isRemote: false,
        publicKey: selfPublicKey,
        clientInfoFacts: new Map(),
        producedFacts: new Set(),
      } satisfies SelfPeer,
    );
  }

  public getPeer(publicKey: Uint8Array): Peer | undefined {
    return this.peers.get(Hash.digest(publicKey).toPrimitive());
  }

  public putPeer(publicKey: Uint8Array): Peer {
    const hash = Hash.digest(publicKey);
    let peer = this.peers.get(hash.toPrimitive());
    if (peer === undefined) {
      peer = {
        isRemote: true,
        // connections: new Set(),
        trust: 0,
        altruism: 0,
        publicKey,
        clientInfoFacts: new Map(),
        producedFacts: new Set(),
      } satisfies RemotePeer & AuthenticatedPeer;
      this.peers.set(hash.toPrimitive(), peer);
    }
    return peer;
  }

  public getAll() {
    return [...this.peers.values()];
  }

  public makeInfo(): PeerInfo {
    const conns = new Set(this.ctx.get(ConnectionService).getAll());

    return {
      timestamp: BigInt(this.ctx.config.timeProvider.now()),
      network: this.ctx.config.network,
      version: 1,
      userdata: this.ctx.config.userdata ?? '',
      clientNonce: this.ctx.config.clientNonce,
      bandwidth: Math.floor(40000 / (conns.size + 1)),
      protocols: this.ctx.get(NetworkService).getProtocolList(),
    };
  }

