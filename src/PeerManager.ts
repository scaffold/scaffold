export interface RemotePeer {
  isRemote: true;

  // The set of currently connected connections
  // connections: Set<Connection>;

  // Trust increases by 1/day
  // Trust decreases when nodes do suspicious things (we should also publish the suspicious things to our peers)
  // If trust is less than -1, disconnect
  // Only connect to peers where trust is greater than 0
  trust: number;

  // TODO: Remove this (it should only be on a Connection)
  // Altruism increases when we recieve helpful facts from the node
  // Altruism decreases when we send (hopefully helpful) facts to the node
  // We publish to positively altruistic nodes
  altruism: number;
}

export interface AuthenticatedPeer {
  publicKey: Uint8Array;

  clientInfoFacts: Map<string, PeerInfoFact>;

  // TODO: Filter this by canonicality
  producedFacts: Set<Fact>;
}

export interface SelfPeer extends AuthenticatedPeer {
  isRemote: false;
}

export type Peer = SelfPeer | (RemotePeer & AuthenticatedPeer);

