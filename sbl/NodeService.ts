// Bitcoin makes these attacks more difficult by only making an outbound connection to one IP address per /16 (x.y.0.0).

// TODO: Maybe split into connected and unconnected nodes. This will help eliminate optionals.
export interface Node {
  hash: Hash;

  // Map from protocols to currently active (but perhaps not yet ready) connections.
  connections: Map<string, {
    tryConnect(spec: string): void;

    // If this is set, the connection is ready.
    conn?: Connection;
  }>;

  // This should be set to the fastest connection ready for sending.
  defaultConn?: Connection;
  // Connection promise?

  lastInfoTime: number;

  // The set of protocols that the node itself has vouched for (not its neighbors)
  handledProtocols?: string[];

  neighbors: Set<Node>;

  // Number of network hops required to reach this node.
  // A path to this node can be recursivly generated by generating a path to it's neighbors where neighbor.hops === node.hops - 1
  hops: number;

  knownFacts: Set<Fact>;

  // Trust increases by 1/day
  // Trust decreases when nodes do suspicious things
  // If trust is less than -1, disconnect
  // Only connect to peers where trust is greater than 0
  trust: number;

  // Benevolence increases when we recieve helpful facts from the node
  // Benevolence decreases when we send (hopefully helpful) facts to the node
  // We publish to positively benevolent nodes
  benevolence: number;
}

